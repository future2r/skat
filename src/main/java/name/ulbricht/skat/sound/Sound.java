package name.ulbricht.skat.sound;

/**
 * The few quiet sounds of the game.
 */
public enum Sound {
    /** A card is laid on the table. */
    CARD,
    /** A trick is collected. */
    COLLECT,
    /** It is the player's turn. */
    TURN,
    /** The player won the game. */
    WON,
    /** The player lost the game. */
    LOST
}
